// Writes the Caddy header snippet for the production export (predeployment-review R10). It is
// generated from this build: the CSP's script hashes come from the exported HTML, and the other
// headers from security-headers.ts, so the served policy can never drift from the build or be
// empty. deploy/Caddyfile imports the file; without it Caddy refuses to start. The snippet is
// written next to the export, not inside it, so it is never served.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CACHE_HASHED_STATIC,
  CACHE_HTML,
  cspProblems,
  STATIC_SECURITY_HEADERS,
} from '../security-headers.ts';
import { exportDir, productionCsp } from './csp-from-export.mjs';

const out = exportDir.pathname;
if (!out.endsWith('/out/'))
  throw new Error('Only the production export (apps/web/out) gets Caddy headers.');
for (const diagnostic of ['csp-probe.html', 'csp-probe', 'diagnostics', 'csp-probe-worker.js'])
  if (existsSync(join(out, diagnostic)))
    throw new Error(`Diagnostic file ${diagnostic} is in the export; refusing to write headers.`);

const csp = await productionCsp();
// Fail closed on anything but a complete, strict policy.
const problems = cspProblems(csp);
if (problems.length > 0) throw new Error(`Refusing to write the CSP: ${problems.join('; ')}.`);

const quoted = (value) => {
  if (/["\n\r{}]/.test(value)) throw new Error(`Header value cannot be quoted: ${value}`);
  return `"${value}"`;
};
const index = readFileSync(join(out, 'index.html'));
const lines = [
  '# Generated by apps/web/scripts/write-caddy-headers.mjs from this build. Do not edit.',
  `# Export index.html SHA-256: ${createHash('sha256').update(index).digest('hex')}`,
  'header {',
  `\tContent-Security-Policy ${quoted(csp)}`,
  ...Object.entries(STATIC_SECURITY_HEADERS).map(([name, value]) => `\t${name} ${quoted(value)}`),
  '\t-Server',
  '}',
  '# Hashed build assets may be cached; every other response, including HTML, RSC payloads,',
  '# errors and the API, is never stored. `>` replaces the value when the response is written,',
  "# so it also replaces the API's own header instead of adding a second one.",
  '# Imported once per route (site, errors); the argument keeps the matcher names distinct.',
  '@hashed_{args[0]} path /_next/static/*',
  `header @hashed_{args[0]} >Cache-Control ${quoted(CACHE_HASHED_STATIC)}`,
  '@unhashed_{args[0]} not path /_next/static/*',
  `header @unhashed_{args[0]} >Cache-Control ${quoted(CACHE_HTML)}`,
  '',
];

const dir = new URL('../out-caddy/', import.meta.url).pathname;
mkdirSync(dir, { recursive: true });
const target = join(dir, 'security-headers.caddy');
writeFileSync(`${target}.partial`, lines.join('\n'), { mode: 0o644 });
renameSync(`${target}.partial`, target);
process.stdout.write(`Wrote ${target}\n`);

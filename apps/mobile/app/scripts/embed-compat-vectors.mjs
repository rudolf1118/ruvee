// Copies the published vector files the portable checks read (tools/crypto-validation/vectors)
// and the committed provisional protocol vectors into one generated module, so the on-device
// compatibility runner can read them without a file system. The checks verify each file's
// SHA-256 against sources.json before parsing it, exactly as in Node and the browsers.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(appRoot, '../../..');
const vectorDir = join(repoRoot, 'tools/crypto-validation/vectors');
const FILES = [
  'sources.json',
  'draft-irtf-cfrg-xchacha-03.txt',
  'wycheproof-xchacha20_poly1305_test.json',
];

const entries = FILES.map(
  (file) =>
    `  ${JSON.stringify(file)}: ${JSON.stringify(readFileSync(join(vectorDir, file)).toString('base64'))},`,
);
const provisional = readFileSync(
  join(repoRoot, 'packages/crypto/test/vectors/provisional-protocol-vectors.json'),
  'utf8',
);
const out = join(appRoot, 'src/compat/generated/vector-files.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  [
    '// Generated by scripts/embed-compat-vectors.mjs. Do not edit.',
    'export const VECTOR_FILES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    `export const PROVISIONAL_VECTORS_JSON = ${JSON.stringify(provisional)};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${out}`);
